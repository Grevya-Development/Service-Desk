export function catalogIcon(name: string | null | undefined): LucideIcon {
  if (!name) return Package;
  const key = name
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
  return ICONS[key] ?? Package;
}

/** Renders the lucide icon for a catalog item's `icon` name. */
export function CatalogIcon({ name, className, style }: { name: string | null | undefined; className?: string; style?: CSSProperties }) {
  return createElement(catalogIcon(name), { className, style, "aria-hidden": true });
}
